export const strings: Record<Lang, Record<StringKey, string>> = { en, tr };

export function translate(lang: Lang, key: StringKey, params?: Record<string, string | number>): string {
  let text = strings[lang][key] ?? strings.en[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }

  return text;
}

/** Message for an error code, falling back to a generic text for unknown codes. */
export function errorText(lang: Lang, code: string | null | undefined): string {
  const key = `errors.${code ?? 'unknown'}` as StringKey;
  return key in strings.en ? translate(lang, key) : translate(lang, 'errors.unknown');
}
